/**
 * Emits the tokens as plain CSS custom properties (dist/tokens.css) and as JSON
 * (dist/tokens.json), so they can be consumed without any build tooling.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as tokens from '../src/index.js'
import {
  colors,
  cssVar,
  colorRefVar,
  duration,
  easing,
  flattenSemantic,
  fontFamily,
  fontSize,
  fontWeight,
  letterSpacing,
  lineHeight,
  radius,
  semanticColors,
  shadow,
  spacing,
  textStyles,
  type SemanticColors,
} from '../src/index.js'

const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '../dist')

const decl = (name: string, value: string) => `  ${cssVar(name)}: ${value};`
const group = (ns: string, values: Record<string, string>) =>
  Object.entries(values).map(([k, v]) => decl(`${ns}-${k}`, v))

const primitives = [
  ...Object.entries(colors).flatMap(([palette, value]) =>
    typeof value === 'string'
      ? [decl(`color-${palette}`, value)]
      : Object.entries(value).map(([scale, v]) => decl(`color-${palette}-${scale}`, v)),
  ),
  ...group('font', fontFamily),
  ...group('text', fontSize),
  ...group('font-weight', fontWeight),
  ...group('leading', lineHeight),
  ...group('tracking', letterSpacing),
  decl('spacing', spacing),
  ...group('radius', radius),
  ...group('shadow', shadow),
  ...group('duration', duration),
  ...group('ease', easing),
]

const textStyleVars = Object.entries(textStyles).flatMap(([name, s]) => [
  decl(`text-${name}-family`, `var(${cssVar(`font-${s.family}`)})`),
  decl(`text-${name}-size`, `var(${cssVar(`text-${s.size}`)})`),
  decl(`text-${name}-weight`, `var(${cssVar(`font-weight-${s.weight}`)})`),
  decl(`text-${name}-leading`, `var(${cssVar(`leading-${s.lineHeight}`)})`),
  decl(`text-${name}-tracking`, `var(${cssVar(`tracking-${s.letterSpacing}`)})`),
])

const semantic = (c: SemanticColors) =>
  flattenSemantic(c).map(([name, ref]) => decl(`color-${name}`, colorRefVar(ref)))

const css = `/* Generated by @octarine/tokens — do not edit. */
:root {
  /* Primitives */
${primitives.join('\n')}

  /* Text styles */
${textStyleVars.join('\n')}

  /* Semantic colors (light) */
  color-scheme: light;
${semantic(semanticColors.light).join('\n')}
}

.dark,
[data-theme='dark'] {
  color-scheme: dark;
${semantic(semanticColors.dark).join('\n')}
}
`

mkdirSync(outDir, { recursive: true })
writeFileSync(resolve(outDir, 'tokens.css'), css)
writeFileSync(
  resolve(outDir, 'tokens.json'),
  JSON.stringify(
    Object.fromEntries(Object.entries(tokens).filter(([, v]) => typeof v !== 'function')),
    null,
    2,
  ) + '\n',
)
console.log('✓ tokens.css, tokens.json')

/**
 * Emits the tokens as plain CSS custom properties and as JSON, so they can be
 * consumed without any build tooling:
 *
 *   dist/tokens.css        global primitives + the default theme (applies on :root)
 *   dist/themes/<name>.css one file per theme, activated with data-theme="<name>"
 *   dist/themes/all.css    every non-default theme
 *   dist/tokens.json
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as tokens from '../src/index.js'
import {
  baseColors,
  cssVar,
  defaultTheme,
  fontSize,
  fontWeight,
  letterSpacing,
  lineHeight,
  spacing,
  themes,
  themeToCss,
} from '../src/index.js'

const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '../dist')
const header = '/* Generated by @octarine/tokens — do not edit. */\n'

const decl = (name: string, value: string) => `  ${cssVar(name)}: ${value};`
const group = (ns: string, values: Record<string, string>) =>
  Object.entries(values).map(([k, v]) => decl(`${ns}-${k}`, v))

const globals = [
  ...Object.entries(baseColors).map(([name, value]) => decl(`color-${name}`, value)),
  ...group('text', fontSize),
  ...group('font-weight', fontWeight),
  ...group('leading', lineHeight),
  ...group('tracking', letterSpacing),
  decl('spacing', spacing),
]

const others = Object.values(themes).filter((t) => t !== defaultTheme)

mkdirSync(resolve(outDir, 'themes'), { recursive: true })
writeFileSync(
  resolve(outDir, 'tokens.css'),
  `${header}:root {\n${globals.join('\n')}\n}\n\n${themeToCss(defaultTheme, { isDefault: true })}`,
)
for (const theme of Object.values(themes)) {
  writeFileSync(resolve(outDir, `themes/${theme.name}.css`), header + themeToCss(theme))
}
writeFileSync(
  resolve(outDir, 'themes/all.css'),
  header + others.map((t) => themeToCss(t)).join('\n'),
)
writeFileSync(
  resolve(outDir, 'tokens.json'),
  JSON.stringify(
    Object.fromEntries(Object.entries(tokens).filter(([, v]) => typeof v !== 'function')),
    null,
    2,
  ) + '\n',
)
console.log(`✓ tokens.css, themes/{${Object.keys(themes).join(',')},all}.css, tokens.json`)

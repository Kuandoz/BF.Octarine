/**
 * Generates dist/theme.css: a Tailwind v4 `@theme inline` block that maps every
 * Tailwind theme variable onto an `--oct-*` token variable. `inline` makes the
 * utilities reference the token variables directly, so a `.dark` subtree that
 * redefines the semantic tokens restyles every utility inside it.
 *
 * Hand-written CSS in src/ is copied to dist/ alongside it.
 */
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  colors,
  cssVar,
  easing,
  flattenSemantic,
  fontFamily,
  fontSize,
  fontWeight,
  letterSpacing,
  lineHeight,
  radius,
  semanticColors,
  shadow,
  textStyles,
} from '@octarine/tokens'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = resolve(root, 'src')
const outDir = resolve(root, 'dist')

const map = (twName: string, tokenName: string) => `  --${twName}: var(${cssVar(tokenName)});`
const group = (tw: string, token: string, values: object) =>
  Object.keys(values).map((k) => map(`${tw}-${k}`, `${token}-${k}`))

const lines = [
  '  /* Only Octarine values: drop Tailwind defaults for these namespaces. */',
  '  --color-*: initial;',
  '  --font-*: initial;',
  '  --text-*: initial;',
  '  --radius-*: initial;',
  '  --shadow-*: initial;',
  '',
  '  /* Primitive palettes */',
  ...Object.entries(colors).flatMap(([palette, value]) =>
    typeof value === 'string'
      ? [map(`color-${palette}`, `color-${palette}`)]
      : Object.keys(value).map((scale) =>
          map(`color-${palette}-${scale}`, `color-${palette}-${scale}`),
        ),
  ),
  '',
  '  /* Semantic colors (switch with .dark / [data-theme=dark]) */',
  ...flattenSemantic(semanticColors.light).map(([name]) => map(`color-${name}`, `color-${name}`)),
  '',
  '  /* Typography */',
  ...group('font', 'font', fontFamily),
  ...group('text', 'text', fontSize),
  ...group('font-weight', 'font-weight', fontWeight),
  ...group('leading', 'leading', lineHeight),
  ...group('tracking', 'tracking', letterSpacing),
  '',
  '  /* Text styles: `text-heading-1` sets size, leading, weight and tracking at once */',
  ...Object.keys(textStyles).flatMap((name) => [
    map(`text-${name}`, `text-${name}-size`),
    map(`text-${name}--line-height`, `text-${name}-leading`),
    map(`text-${name}--font-weight`, `text-${name}-weight`),
    map(`text-${name}--letter-spacing`, `text-${name}-tracking`),
  ]),
  '',
  '  /* Layout & effects */',
  map('spacing', 'spacing'),
  ...group('radius', 'radius', radius),
  ...group('shadow', 'shadow', shadow),
  ...group('ease', 'ease', easing),
]

mkdirSync(outDir, { recursive: true })
writeFileSync(
  resolve(outDir, 'theme.css'),
  `/* Generated by @octarine/tailwind — do not edit. */\n@theme inline {\n${lines.join('\n')}\n}\n`,
)
for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.css'))) {
  copyFileSync(resolve(srcDir, file), resolve(outDir, file))
}
console.log('✓ theme.css + base styles')

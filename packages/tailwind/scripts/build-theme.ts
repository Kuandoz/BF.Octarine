/**
 * Generates the Tailwind side of the tokens:
 *
 * - dist/theme.css: a Tailwind v4 `@theme inline` block that maps every Tailwind
 *   theme variable onto an `--oct-*` token variable. `inline` makes utilities
 *   reference the token variables directly, so any subtree that switches theme
 *   (`data-theme`) or mode (`data-mode`) restyles every utility inside it.
 * - dist/text-styles.css: one `@utility text-<style>` per text style, setting
 *   family, size, leading, weight, tracking and case together.
 *
 * Hand-written CSS in src/ is copied to dist/ alongside them.
 */
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  baseColors,
  colorScales,
  cssVar,
  defaultTheme,
  flattenSemantic,
  fontSize,
  fontWeight,
  letterSpacing,
  lineHeight,
  paletteNames,
  radiusNames,
  shadowNames,
  textStyleNames,
} from '@octarine/tokens'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = resolve(root, 'src')
const outDir = resolve(root, 'dist')
const header = '/* Generated by @octarine/tailwind — do not edit. */\n'

const map = (twName: string, tokenName: string) => `  --${twName}: var(${cssVar(tokenName)});`
const group = (tw: string, token: string, keys: readonly (string | number)[]) =>
  keys.map((k) => map(`${tw}-${k}`, `${token}-${k}`))

const lines = [
  '  /* Only Octarine values: drop Tailwind defaults for these namespaces. */',
  '  --color-*: initial;',
  '  --font-*: initial;',
  '  --text-*: initial;',
  '  --radius-*: initial;',
  '  --shadow-*: initial;',
  '',
  '  /* Primitive palettes (each theme supplies its own values) */',
  ...Object.keys(baseColors).map((c) => map(`color-${c}`, `color-${c}`)),
  ...paletteNames.flatMap((p) => group(`color-${p}`, `color-${p}`, colorScales)),
  '',
  '  /* Semantic colors (switch with data-theme / data-mode) */',
  ...flattenSemantic(defaultTheme.light.colors).map(([name]) =>
    map(`color-${name}`, `color-${name}`),
  ),
  '',
  '  /* Typography (text styles are utilities, see text-styles.css) */',
  ...group('font', 'font', ['sans', 'display', 'mono']),
  ...group('text', 'text', Object.keys(fontSize)),
  ...group('font-weight', 'font-weight', Object.keys(fontWeight)),
  ...group('leading', 'leading', Object.keys(lineHeight)),
  ...group('tracking', 'tracking', Object.keys(letterSpacing)),
  '',
  '  /* Layout & effects */',
  map('spacing', 'spacing'),
  ...group('radius', 'radius', radiusNames),
  ...group('shadow', 'shadow', shadowNames),
  ...group('ease', 'ease', ['standard', 'enter', 'exit']),
  '',
  '  /* Component tokens: rounded-control, shadow-card, … */',
  ...group('radius', 'radius', ['control', 'input', 'card', 'badge']),
  map('shadow-control', 'button-shadow'),
  map('shadow-card', 'card-elevated-shadow'),
]

const textStyles = textStyleNames.map((name) => {
  const v = (prop: string) => `var(${cssVar(`text-${name}-${prop}`)})`
  return `@utility text-${name} {
  font-family: ${v('family')};
  font-size: ${v('size')};
  line-height: ${v('leading')};
  font-weight: ${v('weight')};
  letter-spacing: ${v('tracking')};
  text-transform: ${v('transform')};
}
`
})

mkdirSync(outDir, { recursive: true })
writeFileSync(resolve(outDir, 'theme.css'), `${header}@theme inline {\n${lines.join('\n')}\n}\n`)
writeFileSync(resolve(outDir, 'text-styles.css'), header + textStyles.join('\n'))
for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.css'))) {
  copyFileSync(resolve(srcDir, file), resolve(outDir, file))
}
console.log('✓ theme.css, text-styles.css + base styles')
